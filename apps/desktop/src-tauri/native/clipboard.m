#import <AppKit/AppKit.h>
#include <string.h>

NSPasteboard *clip_history_board(void) {
#ifdef CLIPBOARD_FIXTURE
  static NSPasteboard *board;
  static dispatch_once_t once;
  dispatch_once(&once, ^{
    board = [NSPasteboard pasteboardWithUniqueName];
  });
  return board;
#else
  return NSPasteboard.generalPasteboard;
#endif
}
#ifdef CLIPBOARD_FIXTURE
void clip_fixture_copy(const char *value, int concealed) {
  NSPasteboard *p = clip_history_board();
  [p clearContents];
  [p setString:@(value) forType:NSPasteboardTypeString];
  [p setString:@"TestNotes" forType:@"org.nspasteboard.source"];
  if (concealed)
    [p setString:@"" forType:@"org.nspasteboard.ConcealedType"];
}
#endif

// Only inspect a text or image representation after its privacy markers and
// source passed.
char *clip_source(int allow_image) {
  @autoreleasepool {
    NSPasteboard *board = clip_history_board();
    NSArray *types = board.types;
    for (NSString *type in @[
           @"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType",
           @"org.nspasteboard.AutoGeneratedType", @"com.agilebits.onepassword",
           NSPasteboardTypeFileURL
         ])
      if ([types containsObject:type])
        return NULL;
    BOOL has_text = [types containsObject:NSPasteboardTypeString] ||
                    [types containsObject:NSPasteboardTypeURL];
    BOOL has_image = allow_image &&
                     ([types containsObject:NSPasteboardTypePNG] ||
                      [types containsObject:NSPasteboardTypeTIFF]);
    if (!has_text && !has_image)
      return NULL;
    NSString *source = [types containsObject:@"org.nspasteboard.source"]
                           ? [board stringForType:@"org.nspasteboard.source"]
                           : nil;
    if (!source.length)
      source =
          NSWorkspace.sharedWorkspace.frontmostApplication.bundleIdentifier;
    return source.length ? strdup(source.UTF8String) : NULL;
  }
}
char *clip_plain(void) {
  @autoreleasepool {
    NSPasteboard *pb = clip_history_board();
    NSString *s = [pb stringForType:NSPasteboardTypeString]
                      ?: [pb stringForType:NSPasteboardTypeURL];
    if (!s.length || s.length > 65536 ||
        [s lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > 65536)
      return NULL;
    return strdup(s.UTF8String);
  }
}
uint8_t *clip_image(size_t *out_len, int *out_format) {
  @autoreleasepool {
    if (!out_len || !out_format)
      return NULL;
    *out_len = 0;
    *out_format = 0;
    NSPasteboard *pb = clip_history_board();
    NSData *png = [pb dataForType:NSPasteboardTypePNG];
    if (!png.length) {
      NSData *tiff = [pb dataForType:NSPasteboardTypeTIFF];
      if (!tiff.length || tiff.length > 32 * 1024 * 1024)
        return NULL;
      NSBitmapImageRep *rep = [NSBitmapImageRep imageRepWithData:tiff];
      if (!rep)
        return NULL;
      png = [rep representationUsingType:NSBitmapImageFileTypePNG
                              properties:@{}];
    }
    if (!png.length || png.length > 15 * 1024 * 1024)
      return NULL;
    uint8_t *buf = (uint8_t *)malloc(png.length);
    if (!buf)
      return NULL;
    memcpy(buf, png.bytes, png.length);
    *out_len = png.length;
    *out_format = 1;
    return buf;
  }
}
